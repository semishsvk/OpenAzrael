#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from pathlib import Path

from common import ROOT, sha256_file, write_json
from oa_tex_runtime_verify import verify_manifest

DEFAULT_EXPORT_ROOT = ROOT / ".local/texture_lab/runtime_export"


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def gd_string(value: str) -> str:
    return json.dumps(str(value), ensure_ascii=False)


def render_map(manifest: dict, manifest_sha256: str) -> str:
    rows = sorted(
        [
            row
            for row in manifest.get("textures", [])
            if isinstance(row, dict) and row.get("id")
        ],
        key=lambda row: str(row["id"]),
    )
    lines = [
        "extends RefCounted",
        "",
        "# Generated by oa_tex_runtime_export.py after PASS integrity verification.",
        "# Do not edit by hand.",
        f"const PROFILE := {gd_string(manifest.get('profile', ''))}",
        f"const SOURCE_MANIFEST_SHA256 := {gd_string(manifest_sha256)}",
        "const AUTOMATIC_PROMOTION := false",
        "const TEXTURES := {",
    ]
    for row in rows:
        lines.extend(
            [
                f"    {gd_string(row['id'])}: {{",
                f"        \"path\": {gd_string(row.get('path', ''))},",
                f"        \"tier\": {gd_string(row.get('resolved_tier', ''))},",
                f"        \"sha256\": {gd_string(row.get('sha256', ''))},",
                f"        \"reason\": {gd_string(row.get('resolution_reason', ''))},",
                "    },",
            ]
        )
    lines.extend(
        [
            "}",
            "",
            "static func has_texture(texture_id: String) -> bool:",
            "    return TEXTURES.has(texture_id)",
            "",
            "static func path_for(texture_id: String) -> String:",
            "    if not TEXTURES.has(texture_id):",
            '        return ""',
            '    return String((TEXTURES[texture_id] as Dictionary).get("path", ""))',
            "",
            "static func tier_for(texture_id: String) -> String:",
            "    if not TEXTURES.has(texture_id):",
            '        return ""',
            '    return String((TEXTURES[texture_id] as Dictionary).get("tier", ""))',
            "",
        ]
    )
    return "\n".join(lines)


def compile_export(
    manifest_path: Path,
    root: Path,
    out_script: Path,
    snapshot_path: Path,
) -> dict:
    verification = verify_manifest(manifest_path, root)
    if verification.get("status") != "PASS":
        raise RuntimeError(
            "runtime export requires PASS manifest verification; "
            f"status={verification.get('status')}"
        )

    manifest = load_json(manifest_path)
    manifest_sha = sha256_file(manifest_path)
    script = render_map(manifest, manifest_sha)
    out_script.parent.mkdir(parents=True, exist_ok=True)
    out_script.write_text(script, encoding="utf-8")

    snapshot = {
        "schema": "openazrael.texture_lab.runtime_export_snapshot.v1",
        "status": "READY_FOR_GODOT_IMPORT",
        "profile": manifest.get("profile"),
        "automatic_promotion": False,
        "texture_count": len(manifest.get("textures", [])),
        "source_manifest": {
            "path": str(manifest_path),
            "sha256": manifest_sha,
            "size_bytes": manifest_path.stat().st_size,
        },
        "generated_map": {
            "path": str(out_script),
            "sha256": sha256_file(out_script),
            "size_bytes": out_script.stat().st_size,
        },
        "pre_export_verification": verification,
        "runtime_loading_contract": (
            "Generated map is data-only. Exported Godot runtime must load the "
            "resolved res:// texture paths via ResourceLoader rather than raw "
            "FileAccess hashing of imported texture source files."
        ),
    }
    write_json(snapshot_path, snapshot)
    return snapshot


def main() -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Compile a PASS-verified runtime texture manifest into a static "
            "Godot-friendly map plus immutable export snapshot metadata."
        )
    )
    parser.add_argument("manifest", type=Path)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument(
        "--out-script",
        type=Path,
        default=DEFAULT_EXPORT_ROOT / "texture_runtime_map.gd",
    )
    parser.add_argument(
        "--snapshot",
        type=Path,
        default=DEFAULT_EXPORT_ROOT / "runtime_export_snapshot.json",
    )
    args = parser.parse_args()

    try:
        snapshot = compile_export(
            args.manifest,
            args.root,
            args.out_script,
            args.snapshot,
        )
    except RuntimeError as exc:
        print(f"HOLD runtime_export {exc}")
        return 1

    print(
        f"PASS runtime_export profile={snapshot['profile']} "
        f"textures={snapshot['texture_count']} "
        f"map={args.out_script} snapshot={args.snapshot}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
